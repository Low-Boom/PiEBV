def harness_case(vcam, corner, load, length_m, rs=None, net="Trigger3", pin="J3.4", out="U6.6"):
    """rs: value of the on-board series resistor (None: the fitted value; 0: as Rev 1, no resistor)."""
    g = (R2["gates_3v3"] if vcam > 2.5 else BASE_GATES)["SN74LVC04A"]
    vk = "v3v3" if vcam > 2.5 else "v1v8"
    amp = {"min": "max", "typ": "typ", "max": "min"}[corner]      # fast corner = high supply
    v = R2["vcam"][vk][amp]
    c = S.Ckt("harness %s %s %s %.1f m" % (vcam, corner, load, length_m), S.TMAX_PS)
    ta, tb, te = 5.0, 105.0, 205.0
    r = g["rout"][corner]
    S.add_switch_out(c, "u6", node(out), v, r, r, g["ramp_ns_est"][corner], ta, tb, start_high=False)
    c.cam_net(net, rs)
    c.C(node(pin), S.BP["header_pin_pF_est"])
    c.R(node(pin), "hw_in", max(H["r_ohm_per_m"] * length_m * 2, 1e-3))        # wire resistance, signal and return
    c.T("hw_in", "cam", H["z0_ohm"], H["td_ns_per_m"] * length_m)
    if load == "evk4":
        c.add(".model DOPTO D(IS=%g N=%g RS=1)" % (E4["led_is"], E4["led_n"]))
        c.R("cam", "led_a", E4["r_series_ohm"])
        c.add("D%s led_a 0 DOPTO" % c.uid())
        c.C("cam", E4["c_pF"])
    else:
        c.C("cam", R2["ids_input"]["c_pF"])
        c.R("cam", "0", 1e7)
    c.tran(te)
    t, w = sp.run(c.lines, [node(pin), "cam"] + (["led_a"] if load == "evk4" else []))
    vc = w["cam"]
    hi = float(vc[(t > tb - 5) & (t < tb)].mean())
    lo = float(vc[t > te - 5].mean())
    res = dict(v_supply=v, high=hi, low=lo, vmax=float(vc[(t >= ta) & (t < tb)].max()), vmin=float(vc[t >= tb].min()),
               t50_rise=S.cross(t, vc, v / 2, True, ta, tb) - ta, t50_fall=S.cross(t, vc, v / 2, False, tb, te) - tb)
    if load == "evk4":
        res["i_led_mA"] = 1e3 * (hi - float(w["led_a"][(t > tb - 5) & (t < tb)].mean())) / E4["r_series_ohm"]
        res["t_vih_rise"] = S.cross(t, vc, E4["vih_min"], True, ta, tb) - ta
        res["t_vil_fall"] = S.cross(t, vc, E4["vil_max"], False, tb, te) - tb
        res["ring_low_after_rise"] = float(vc[(t > ta + res["t_vih_rise"] + 0.5) & (t < tb)].min())
        res["ring_high_after_fall"] = float(vc[(t > tb + res["t_vil_fall"] + 0.5)].max())
    return res


