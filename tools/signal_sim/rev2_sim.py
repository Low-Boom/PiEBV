def gap_case(w, zgap, egap, l1, l2, vdrv, rdrv, ramp):
    lay = lay_of(w)
    out = {}
    for with_gap in (False, True):
        c = S.Ckt("gap %s" % with_gap, 1.0)
        ta, tb = 2.0, 22.0
        S.add_switch_out(c, "d", "src", vdrv, rdrv, rdrv, ramp, ta, tb, start_high=False)
        c.T("src", "g1", lay["z0_ohm"], lay["td_ps_per_mm"] * l1 * 1e-3)
        if with_gap:
            td = PG["run_mm"] * np.sqrt(egap) / 299.792458             # ns
            c.C("g1", td / zgap * 1e3 / 2)
            c.L("g1", "g2", zgap * td)
            c.C("g2", td / zgap * 1e3 / 2)
        else:
            c.T("g1", "g2", lay["z0_ohm"], lay["td_ps_per_mm"] * PG["run_mm"] * 1e-3)
        c.T("g2", "rx", lay["z0_ohm"], lay["td_ps_per_mm"] * l2 * 1e-3)
        c.C("rx", 5.0)
        c.tran(40.0)
        t, wv = sp.run(c.lines, ["src", "rx"])
        out[with_gap] = (t, wv["rx"], wv["src"])
    t0, r0, s0 = out[False]
    t1, r1, s1 = out[True]
    d = S.cross(t1, r1, vdrv / 2, True, 2.0, 22.0) - S.cross(t0, r0, vdrv / 2, True, 2.0, 22.0)
    r1i = np.interp(t0, t1, r1)
    return dict(delay_ps=1e3 * d, max_dev_mV=1e3 * float(np.abs(r1i - r0).max()))


